/**
 * Assembles dist/arey.css: arey's own self-contained stylesheet (tokens + vendored
 * Phosphor fonts) plus its component CSS, harvested at build time.
 *
 * Why the harvest: arey ships each component's CSS inside its JS module and injects it
 * into `document.head` on first import (arey's components/internal/sheet.jsx). That
 * injector no-ops when `document` is undefined, so SSR would otherwise ship unstyled
 * markup that visibly restyles on hydration. So: bundle `@hamsa-designs/arey/react`,
 * import it under a minimal document shim that captures `head.appendChild`, and write
 * what it collected alongside arey's vendored tokens/fonts into one static file every
 * consuming app imports — no per-app harvest step required.
 *
 * Run via `pnpm build` (after tsup). Output is generated, not committed.
 */
import { build } from 'esbuild';
import { cpSync } from 'node:fs';
import { mkdir as mkdirP, rm as rmP, writeFile as writeFileP } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);
const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(packageRoot, 'dist');
const vendorAreyDir = path.join(distDir, 'vendor', 'arey');
const bundlePath = path.join(packageRoot, 'node_modules', '.cache', 'arey-css-extract.mjs');

interface CapturedElement {
  tagName: string;
  textContent: string;
  href: string;
  setAttribute(name: string, value: string): void;
}

function areyDistDir(): string {
  // No "./package.json" export subpath, so resolve via a real export ("./react" ->
  // ".../dist/index.js") and walk up to the package's dist/ directory.
  const reactEntry = require.resolve('@hamsa-designs/arey/react');
  return path.dirname(reactEntry);
}

async function bundleAreyReact(): Promise<void> {
  await mkdirP(path.dirname(bundlePath), { recursive: true });
  await build({
    entryPoints: ['@hamsa-designs/arey/react'],
    outfile: bundlePath,
    absWorkingDir: packageRoot,
    bundle: true,
    format: 'esm',
    platform: 'node',
    external: ['react', 'react/jsx-runtime'],
    logLevel: 'error',
  });
}

async function collectComponentCss(): Promise<string[]> {
  const sheets: string[] = [];

  // Minimal shim. arey only ever calls createElement + head.appendChild.
  (globalThis as { document?: unknown }).document = {
    createElement(tagName: string): CapturedElement {
      return {
        tagName,
        textContent: '',
        href: '',
        setAttribute(name: string, value: string) {
          (this as unknown as Record<string, string>)[name] = value;
        },
      };
    },
    head: {
      appendChild(element: CapturedElement) {
        if (element.tagName === 'style' && element.textContent) sheets.push(element.textContent);
      },
    },
  };

  await import(pathToFileURL(bundlePath).href);
  return sheets;
}

async function main(): Promise<void> {
  const areyDist = areyDistDir();

  // Vendor arey's self-contained styles.css + its vendor/tokens/assets directories alongside it,
  // so the final dist/arey.css only ever uses relative @import — no bare specifiers, no
  // bundler required to consume it.
  await rmP(vendorAreyDir, { recursive: true, force: true });
  cpSync(path.join(areyDist, 'styles.css'), path.join(vendorAreyDir, 'styles.css'));
  cpSync(path.join(areyDist, 'vendor'), path.join(vendorAreyDir, 'vendor'), { recursive: true });
  cpSync(path.join(areyDist, 'tokens'), path.join(vendorAreyDir, 'tokens'), { recursive: true });
  cpSync(path.join(areyDist, 'assets'), path.join(vendorAreyDir, 'assets'), { recursive: true });

  await bundleAreyReact();
  const sheets = await collectComponentCss();
  await rmP(bundlePath, { force: true });

  if (sheets.length === 0) {
    throw new Error(
      'No component stylesheets captured. arey\'s injection mechanism ' +
        '(components/internal/sheet.jsx) has changed; inspect it before trusting this build.',
    );
  }

  const header = [
    '/* GENERATED by scripts/build-arey-css.ts. Do not edit.',
    ' * arey tokens + vendored icon fonts, then harvested component CSS.',
    ' * Regenerate with `pnpm build`.',
    ' */',
    '',
    '@import url("./vendor/arey/styles.css");',
    '',
  ].join('\n');

  await mkdirP(distDir, { recursive: true });
  await writeFileP(path.join(distDir, 'arey.css'), header + sheets.join('\n') + '\n', 'utf8');

  console.log(`arey.css: vendored tokens/fonts + ${sheets.length} component sheets -> dist/arey.css`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
