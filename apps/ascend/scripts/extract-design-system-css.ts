/**
 * Extract @hamsa-designs/arey component CSS to a static stylesheet.
 *
 * Why this exists: arey ships each component's CSS inside its JS module and
 * appends it to document.head on first import (components/internal/sheet.jsx).
 * The injector no-ops when `document` is undefined, so a server render emits
 * correctly structured but completely unstyled HTML, and the page restyles on
 * hydration. On a design built from translucent glass surfaces that flash is
 * very visible.
 *
 * So: bundle the package, import it under a minimal document shim that captures
 * head.appendChild, and write what it collected to a real stylesheet the root
 * layout imports statically. Runtime injection then finds nothing left to do.
 *
 * Run via `predev` / `prebuild`. Output is generated, not committed.
 */
import { build } from 'esbuild';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';

const projectRoot = process.cwd();
const outputPath = join(projectRoot, 'src/generated/arey-components.css');
const bundlePath = join(projectRoot, 'node_modules/.cache/arey-extract.mjs');

interface CapturedElement {
  tagName: string;
  textContent: string;
  href: string;
  setAttribute(name: string, value: string): void;
}

async function bundleDesignSystem(): Promise<void> {
  await mkdir(dirname(bundlePath), { recursive: true });
  await build({
    entryPoints: ['@hamsa-designs/arey/react'],
    outfile: bundlePath,
    absWorkingDir: projectRoot,
    bundle: true,
    format: 'esm',
    platform: 'node',
    jsx: 'automatic',
    loader: { '.jsx': 'jsx' },
    external: ['react', 'react/jsx-runtime'],
    logLevel: 'error',
  });
}

async function collectInjectedStyles(): Promise<{ sheets: string[]; fontHrefs: string[] }> {
  const sheets: string[] = [];
  const fontHrefs: string[] = [];

  // Minimal shim. arey only ever calls createElement + head.appendChild.
  (globalThis as { document?: unknown }).document = {
    createElement(tagName: string): CapturedElement {
      return {
        tagName,
        textContent: '',
        href: '',
        setAttribute(name: string, value: string) {
          (this as unknown as Record<string, string>)[name] = value;
        },
      };
    },
    head: {
      appendChild(element: CapturedElement) {
        if (element.tagName === 'style' && element.textContent) sheets.push(element.textContent);
        else if (element.href) fontHrefs.push(element.href);
      },
    },
  };

  // Side-effect import: injectSheet runs at module scope.
  await import(pathToFileURL(bundlePath).href);

  return { sheets, fontHrefs };
}

async function main(): Promise<void> {
  await bundleDesignSystem();
  const { sheets, fontHrefs } = await collectInjectedStyles();

  if (sheets.length === 0) {
    throw new Error(
      'No stylesheets captured. The arey injection mechanism has changed; ' +
        'inspect components/internal/sheet.jsx before trusting the build.',
    );
  }

  const header = [
    '/* GENERATED by scripts/extract-design-system-css.ts. Do not edit.',
    ` * Source: @hamsa-designs/arey — ${sheets.length} component stylesheets.`,
    ' * Regenerate with `pnpm design-system:css`.',
    ' */',
    '',
  ].join('\n');

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, header + sheets.join('\n') + '\n', 'utf8');
  await rm(bundlePath, { force: true });

  const bytes = sheets.join('\n').length;
  console.log(`arey css: ${sheets.length} sheets, ${bytes} bytes -> src/generated/arey-components.css`);

  // See architecture §12.3. These are fetched from a third-party CDN at runtime,
  // which is an awkward footnote on a landing page arguing nothing leaves the house.
  if (fontHrefs.length > 0) {
    console.warn(`arey css: ${fontHrefs.length} icon font stylesheets still load from a CDN:`);
    for (const href of fontHrefs) console.warn(`  ${href}`);
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
